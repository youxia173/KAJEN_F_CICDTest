// Must match with Matter Light endpoint
#define LIGHT_ENDPOINT 1

// Time it takes in ms for the simulated actuator to move from one
// state to another.
#define ACTUATOR_MOVEMENT_PERIOD_MS 10

// 未配网呼吸灯时序（单位 ms）
#define APP_COMMISSIONING_WINDOW_MS (15u * 60u * 1000u) // 配网窗口总时长 15 分钟
#define APP_BOOT_BREATH_MS (60u * 1000u)                // 呼吸效果最长持续 60 秒（超时强制结束）
// 单个呼吸周期四段：渐亮 → 保持最亮 → 渐灭 → 保持熄灭
#define APP_BOOT_BREATH_RAMP_MS 900u       // 渐亮/渐灭各 900ms（峰顶曲率更平顺）
#define APP_BOOT_BREATH_TOP_HOLD_MS 600u   // 最亮保持 600ms（缩短以减少峰顶停顿感）
#define APP_BOOT_BREATH_OFF_HOLD_MS 800u   // 最暗保持 800ms
#define APP_BOOT_BREATH_CYCLE_MS (APP_BOOT_BREATH_RAMP_MS + APP_BOOT_BREATH_TOP_HOLD_MS + APP_BOOT_BREATH_RAMP_MS + APP_BOOT_BREATH_OFF_HOLD_MS) // 3200ms/周期
#define APP_DOUBLE_CLICK_WINDOW_MS 1000u
#define APP_LONG_PRESS_DIM_START_MS 500u
// 长按恢复出厂：按住满 13s 触发；第 8s 起红灯快闪预警，松手则取消并恢复原状态
#define APP_LONG_PRESS_RESET_WARN_MS 8000u
#define APP_LONG_PRESS_RESET_MS 13000u
// 复位完成后冷启动确认灯效：65% 白光 OFF-ON-OFF-ON-OFF，再淡入出厂呼吸/配网
#define APP_RESET_COMPLETE_BLINK_MS 200u
#define APP_RESET_COMPLETE_LEVEL_PCT 65u

// AppTask queue: default SDK size (10) overflows when Matter/Zigbee/timers burst.
// Button + effect(10ms) + actuator posts compete; 32 still overflows under ChipStack stalls.
#ifndef APP_EVENT_QUEUE_SIZE
#define APP_EVENT_QUEUE_SIZE 64
#endif

// Lighting transition timings
#define APP_ONOFF_FADE_MS 400u
#define APP_COLOR_FADE_MS 400u
// 长按调光：最低亮度(APP_BUTTON_LEVEL_MIN)↔最高(APP_LEVEL_MAX) 全程耗时 APP_DIMMING_PERIOD_MS
#define APP_LEVEL_MAX 254u
#define APP_BUTTON_LEVEL_MIN 26u // 10% — 按键长按调光下限；OnOff 效应不应把记忆亮度降到设备 MinLevel(1)
#define APP_DIMMING_PERIOD_MS 3000u
// 调光刷新步进：20ms≈50fps，与颜色渐变定时器一致。30ms(≈33fps) 的逐帧刷新会落在可见闪烁频段。
// 注意：长按计时(sLongPressMs)与亮度速度均基于真实时间/elapsed，改此值不影响调光速度与长按判定。
#define APP_DIMMING_STEP_MS 20u

// Effect timings
// 效果定时器步进（呼吸/Identify/重置警告等共用）；10ms 一步，800ms 渐亮段约 80 步
#define APP_EFFECT_TICK_MS 10u
#define APP_BOOT_BREATH_PEAK_W 100u
#define APP_RESET_WARN_BLINK_MS 400u
// 兼容旧收尾路径（当前满 13s 已直接恢复出厂，不再播放红灯慢闪）
#define APP_RESET_WARN_END_OFF_MS 1200u
#define APP_RESET_WARN_END_ON_MS 1200u
#define APP_PAIR_SUCCESS_BLINK_ON_MS 200u
#define APP_PAIR_SUCCESS_BLINK_OFF_MS 200u      
// 第 N 次 CommissioningComplete 触发配网成功快闪。
// 注意：Apple/IKEA 有时会连发 2 次，Google/Amazon 通常只发 1 次。
// 必须用 1，否则谷歌/亚马逊会一直卡在开机白光呼吸且不闪成功灯。
#define APP_PAIR_SUCCESS_COMPLETE_COUNT 1u
#define APP_IDENTIFY_BLINK_MS 400u

// SL9003 线性调光：1.1V~3.1V 控制脚，MCU PWM 满幅 3.3V
// 占空比 1.1/3.3≈33.3%，3.1/3.3≈93.9%；逻辑亮度 0 仍为 PWM 关断(0%)
#define APP_WHITE_PWM_SUPPLY_MV 3300u
#define APP_SL9003_DIM_MIN_MV 200u  //最小0.2V
#define APP_SL9003_DIM_MAX_MV 3100u  //最大3.1V ≈93.9%
#define APP_WHITE_PWM_DUTY_MIN_PERMILLE ((APP_SL9003_DIM_MIN_MV * 1000u) / APP_WHITE_PWM_SUPPLY_MV)
#define APP_WHITE_PWM_DUTY_MAX_PERMILLE ((APP_SL9003_DIM_MAX_MV * 1000u) / APP_WHITE_PWM_SUPPLY_MV)
